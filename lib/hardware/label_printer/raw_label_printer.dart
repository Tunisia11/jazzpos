import 'dart:async';
import 'dart:io';
import 'dart:typed_data';

import 'package:tracepos/core/logging/pos_logger.dart';
import 'package:tracepos/hardware/receipt_printer/windows_raw_print_bridge.dart';

import 'label_document.dart';
import 'label_printer_interface.dart';
import 'tspl_commands.dart';

/// How raw TSPL bytes reach the label printer.
enum LabelTransport { network, windowsSpooler, macCups }

extension LabelTransportKey on LabelTransport {
  String get key => switch (this) {
    LabelTransport.network => 'NETWORK',
    LabelTransport.windowsSpooler => 'WINDOWS_SPOOLER',
    LabelTransport.macCups => 'MACOS_CUPS',
  };

  static LabelTransport? fromKey(String? key) {
    for (final t in LabelTransport.values) {
      if (t.key == key) return t;
    }
    return null;
  }
}

/// Sends the TSPL generated by [TsplCommands] to a real label printer.
class RawLabelPrinter implements LabelPrinter {
  RawLabelPrinter({
    required this.queueName,
    required this.transport,
    this.ipAddress,
    this.port = 9100,
    this.timeout = const Duration(seconds: 10),
  });

  final String queueName;
  final LabelTransport transport;
  final String? ipAddress;
  final int port;
  final Duration timeout;

  /// Test hook: receives the bytes instead of a real device.
  Future<void> Function(Uint8List bytes)? sender;

  @override
  String get name => queueName;

  @override
  String get connectionType => transport.key;

  @override
  Future<bool> connect() async => isConnected();

  @override
  Future<bool> isConnected() async {
    if (transport == LabelTransport.network) {
      try {
        final socket = await Socket.connect(
          ipAddress ?? '',
          port,
          timeout: const Duration(seconds: 3),
        );
        await socket.close();
        return true;
      } catch (e) {
        PosLogger.instance.warning('LabelPrinter', 'Unreachable $name: $e');
        return false;
      }
    }
    return queueName.trim().isNotEmpty;
  }

  @override
  Future<void> printLabel(LabelDocument document) async {
    final tspl = TsplCommands.buildLabel(document);
    await _send(Uint8List.fromList(tspl.codeUnits));
    PosLogger.instance.info(
      'LabelPrinter',
      'Sent label ${document.sku} x${document.copies} to $name',
    );
  }

  @override
  Future<void> printBatch(List<LabelDocument> documents) async {
    if (documents.isEmpty) return;
    final buffer = StringBuffer();
    for (final doc in documents) {
      buffer.write(TsplCommands.buildLabel(doc));
    }
    await _send(Uint8List.fromList(buffer.toString().codeUnits));
  }

  @override
  Future<void> disconnect() async {}

  Future<void> _send(Uint8List bytes) async {
    final custom = sender;
    if (custom != null) return custom(bytes);
    switch (transport) {
      case LabelTransport.network:
        final host = ipAddress;
        if (host == null || host.isEmpty) {
          throw Exception('Label printer IP address is not configured');
        }
        final socket = await Socket.connect(host, port, timeout: timeout);
        try {
          socket.add(bytes);
          await socket.flush();
        } finally {
          await socket.close();
        }
      case LabelTransport.windowsSpooler:
        await _viaTempFile(bytes, (path) async {
          final result = await Process.run('powershell', WindowsRawPrintBridge
              .arguments({'queueName': queueName, 'filePath': path}, print: true))
              .timeout(timeout);
          if (result.exitCode != 0) {
            throw Exception('Label spooler error: ${result.stdout}');
          }
        });
      case LabelTransport.macCups:
        await _viaTempFile(bytes, (path) async {
          final result = await Process.run('lp', [
            '-d',
            queueName,
            '-o',
            'raw',
            path,
          ]).timeout(timeout);
          if (result.exitCode != 0) {
            throw Exception('CUPS error: ${result.stderr}');
          }
        });
    }
  }

  Future<void> _viaTempFile(
    Uint8List bytes,
    Future<void> Function(String path) run,
  ) async {
    final dir = await Directory.systemTemp.createTemp('trace_label_');
    final file = File('${dir.path}${Platform.pathSeparator}label.tspl');
    try {
      await file.writeAsBytes(bytes, flush: true);
      await run(file.path);
    } finally {
      try {
        await dir.delete(recursive: true);
      } catch (e) {
        PosLogger.instance.warning('LabelPrinter', 'Temp cleanup failed: $e');
      }
    }
  }
}
